function dedupe(entries: WordEntry[]): WordEntry[] {
  const seen = new Set<string>();
  const out: WordEntry[] = [];
  for (const e of entries) {
    const w = e.word.toUpperCase();
    if (seen.has(w)) continue;
    seen.add(w);
    out.push({ word: w, clue: e.clue });
  }
  return out;
}
